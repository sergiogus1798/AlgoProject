"""Read a .sqx strategy without SQX. It is a ZIP; everything useful is in its inner XML."""

import os
import hashlib
import re
import zipfile
from pathlib import Path
from typing import TypedDict, cast
from xml.etree import ElementTree

import numpy as np

INNER = "strategy_Portfolio.xml"
# 🔬 2026-09-23: a retest rewrites `makeExternal` on every <variable> and changes nothing
# else. Hashing the raw XML therefore gives a strategy one identity in the build databank
# and another in the retest one -- 0 of 115 matched. Stripping it: 115 of 115.
# 🔬 2026-09-27: after the MC Retest SQX also drops `autoGenerated="true"` from every
# <variable>, in the databank it read -- the identity changed in place and /curate refused a
# verdict written an hour earlier. Stripped too (owner, 2026-09-27).
# 🔬 2026-10-04: the pattern carries no leading `\s*` -- `_hashed` strips that whitespace
# itself. Led by `\s*` the regex cost 1.2 ms per strategy: 11.6 s over the 10,000 of one
# databank against 2.2 s, the same 10,000 hashes.
COSMETIC = re.compile(r'(?:makeExternal|autoGenerated)="[^"]*"')
# 🔬 2026-10-12: the four signal variables are saved with the value the LAST bar of the last
# backtest left in them, so a strategy whose entry held on the final bar of the build and not
# on the retest's changed identity between Results and OOS (4 of 6 with a random entry, 83 of
# 400 files of a real build hold a `true`) and the harvest stopped on «same name, other
# identity». Hashed as `false`, what nearly every file carries: an identity that never held a
# `true` does not move. The 94 of the store's 866 that did were migrated that day.
SIGNAL = re.compile(
    r"(<name>(?:Long|Short)(?:Entry|Exit)Signal</name>\s*<type>boolean</type>\s*<value>)true(?=</value>)"
)
# 🔬 2026-10-05: SQX writes an SPP result's `optimizationProfile.bin` in another byte order on
# every save -- same size, same bytes sorted, 894,174 positions moved of 19.5 MB -- so its CRC
# moved at every stop and both SPP databanks were re-exported each time (~40 s per stop).
UNORDERED = ("optimizationProfile.bin",)
BLOCK_KEY = re.compile(r'<Item[^>]*\bkey="([^"]+)"')
RESULTS_RE = re.compile(r"Results/[^:]*:\s*([A-Za-z0-9.@]+)_([^/]*)/")
# The five paramType strings the corrected "Param Count" counts (knowhow/columns/param-count.md,
# fixed 2026-09-06): Period, Constant, EntryLevel, OtherParam, ExitUsed. Excludes MagicNumber,
# the four signal variables and Shift — none carries a paramType SQX ever sets.
COUNTED_PARAM_TYPES = frozenset(
    {
        "ParamTypePeriod",
        "ParamTypeConstant",
        "ParamTypeEntryLevel",
        "ParamTypeOtherParam",
        "ParamTypeExitUsed",
    }
)
_SEEN: dict[tuple[str, int, int], str] = {}  # (path, size, mtime_ns) → identity


def identity(path: Path) -> str:
    """Stable identity of a strategy.

    Args:
        path: A .sqx file.

    Returns:
        SHA-256 of the inner strategy_Portfolio.xml with SQX's own bookkeeping stripped.
        Never hash the .sqx itself: the ZIP embeds timestamps, so identical strategies get
        different file hashes. And never hash the XML raw either — a retest flips
        `makeExternal` on every variable, so the same strategy carries one hash in the
        build databank and a different one in the retest databank, which is exactly the
        join those two databanks have to be paired on. Remembered per path, size and
        mtime: a process that lists a databank twice opens each archive once.
    """
    st = path.stat()
    key = (str(path), st.st_size, st.st_mtime_ns)
    if key not in _SEEN:
        _SEEN[key] = _hashed(rules(path))
    return _SEEN[key]


def remember(path: Path, found: str, st: os.stat_result) -> None:
    """Hand identity() a hash computed elsewhere (a fanout child), under `st = path.stat()` taken before."""
    _SEEN[(str(path), st.st_size, st.st_mtime_ns)] = found


def mark(z: zipfile.ZipFile, entry: zipfile.ZipInfo) -> str:
    """What one non-XML zip entry is: its CRC, or for an `UNORDERED` entry the hash of how
    many times each byte value occurs, which no reordering moves."""
    if not entry.filename.endswith(UNORDERED):
        return str(entry.CRC)
    counts = np.bincount(np.frombuffer(z.read(entry), np.uint8), minlength=256)
    return hashlib.blake2b(counts.tobytes(), digest_size=16).hexdigest()


def _hashed(text: str) -> str:
    """identity() of a strategy definition already read out of its archive."""
    if "Signal</name>" in text:
        text = SIGNAL.sub(r"\1false", text)
    kept, last = [], 0
    for m in COSMETIC.finditer(text):
        kept.append(text[last : m.start()].rstrip())
        last = m.end()
    kept.append(text[last:])
    return hashlib.sha256("".join(kept).encode("utf-8")).hexdigest()


def describe(path: Path) -> tuple[str, str, str]:
    """identity() and symbol() together, from one opening of the archive.

    Args:
        path: A .sqx file.

    Returns:
        (identity, symbol, feed). Reading a ZIP's directory is most of what either costs on
        its own -- a result-laden .sqx carries some 250 entries -- so a scan that wants both
        opens it once. 🔬 2026-09-25, `index_sqx` over 19,328 files was paying it twice.
    """
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        if INNER not in names:
            raise ValueError(f"{path}: no {INNER} — not a strategy .sqx")
        text = z.read(INNER).decode("utf-8", "replace")
    if not text.rstrip().endswith("</StrategyFile>"):
        raise ValueError(f"{path}: {INNER} is not a whole StrategyFile")
    found = next((m for m in map(RESULTS_RE.search, names) if m), None)
    symbol, feed = (found.group(1), found.group(2)) if found else ("", "")
    return _hashed(text), symbol, feed


def rules(path: Path) -> str:
    """The strategy's definition, as text.

    Args:
        path: A .sqx file.

    Returns:
        The inner strategy_Portfolio.xml decoded. Everything that says what the strategy
        DOES is in here; the rest of the archive is results.
    """
    with zipfile.ZipFile(path) as z:
        if INNER not in z.namelist():
            raise ValueError(f"{path}: no {INNER} — not a strategy .sqx")
        text = z.read(INNER).decode("utf-8", "replace")
    if not text.rstrip().endswith("</StrategyFile>"):
        raise ValueError(f"{path}: {INNER} is not a whole StrategyFile")
    return text


def structure(path: Path) -> str:
    """Identity of a strategy's LOGIC, ignoring what its parameters are set to.

    Args:
        path: A .sqx file.

    Returns:
        SHA-256 over the ordered block keys of the strategy. Two strategies share it when
        they are the same rules at different settings — a moving average of 14 and one of
        90 are one idea, not two. On the 115 of a sample build that is 24 distinct shapes,
        two of them holding 32 strategies each: the population is a sixth as diverse as
        its count suggests.
    """
    return hashlib.sha256("|".join(BLOCK_KEY.findall(rules(path))).encode()).hexdigest()


def symbol(path: Path) -> tuple[str, str]:
    """Symbol and data feed a strategy was tested on.

    Args:
        path: A .sqx file.

    Returns:
        (symbol, feed), e.g. ("XAUUSD", "DukasM1_Infinox_LOM_M30"), read from the ZIP
        entry names. Far cheaper than opening the multi-MB settings.xml.
    """
    with zipfile.ZipFile(path) as z:
        for name in z.namelist():
            m = RESULTS_RE.search(name)
            if m:
                return m.group(1), m.group(2)
    return "", ""


def xml(path: Path) -> ElementTree.Element:
    """Parsed strategy definition.

    Args:
        path: A .sqx file.

    Returns:
        Root element of strategy_Portfolio.xml — the rules, parameters and orders.
    """
    with zipfile.ZipFile(path) as z:
        if INNER not in z.namelist():
            raise ValueError(f"{path}: no {INNER} — not a strategy .sqx")
        root = ElementTree.fromstring(z.read(INNER))
    if not (root.tag == "StrategyFile" and root.find("Strategy") is not None):
        raise ValueError(
            f"{path}: {INNER} root is {root.tag}, expected StrategyFile/Strategy"
        )
    return root


def parameters(path: Path) -> dict[str, str]:
    """Every named parameter of a strategy and its value.

    Args:
        path: A .sqx file.

    Returns:
        Parameter name to value as stored, e.g. {"#Size#": "0.1"}. The value is the
        element's text, not an attribute.
    """
    return {
        cast(str, p.get("key")): (p.text or "").strip() for p in xml(path).iter("Param")
    }


def param_count(path: Path) -> int:
    """The "Param Count" column, recomputed from `<Variables>` — never SQX's stored value.

    Args:
        path: A .sqx file.

    Returns:
        How many `<variable>` elements carry a `<paramType>` in `COUNTED_PARAM_TYPES`. SQX
        stores this count in the result it computes it under and never recomputes it
        (`compute()` runs once), so every strategy built before 2026-09-06 carries the old,
        inflated value forever (`knowhow/columns/param-count.md`). This mirrors the fixed
        Java logic directly off the strategy definition, so it is right for every strategy
        regardless of when it was built or last retested.
    """
    return sum(
        1
        for v in xml(path).iter("variable")
        if v.findtext("paramType") in COUNTED_PARAM_TYPES
    )


# 🔬 2026-10-04: the constants of com.strategyquant.tradinglib.BadStrategyException
# (internal/libs/SQTradingLib.jar, read from its class file). Bit 128 has no constant.
PROBLEM_BITS = {
    1: "NoTrades",
    2: "TooLittleTrades",
    4: "ZeroPLTrades",
    8: "TooShortTrades",
    16: "ZeroDurationTrades",
    32: "TooManyOpenTrades",
    64: "TooLongTrade",
    256: "NoFilledTrades",
    512: "OutlierTrade",
    1024: "AmbiguousTrades",
    2048: "StockpickerShiftChanged",
}


class Problems(TypedDict):
    """SQX's Strategy Problems flag, decoded."""

    value: int
    reasons: list[str]
    unknown: int


def strategy_problems(path: Path) -> Problems:
    """SQX's own «Strategy Problems» flag of a strategy.

    Args:
        path: A .sqx file.

    Returns:
        {"value": the bitmask (settings.xml StrategyProblems, 0 when absent),
        "reasons": the BadStrategyException names of the bits set, "unknown": bits set with
        no constant}.
    """
    with zipfile.ZipFile(path) as z:
        found = re.search(
            r"<StrategyProblems[^>]*>(\d+)<",
            z.read("settings.xml").decode("utf-8", "replace"),
        )
    value = int(found.group(1)) if found else 0
    return {
        "value": value,
        "reasons": [n for b, n in PROBLEM_BITS.items() if value & b],
        "unknown": value & ~sum(PROBLEM_BITS),
    }


def sqx_filter(path: Path) -> str | None:
    """SQX's own pass or fail note on a strategy, as its last filtering task left it.

    Args:
        path: A .sqx file.

    Returns:
        The text of `<FiltersResultFailedReason>` in settings.xml — "Passed", or the reason,
        e.g. "Cross Check filter in 'Walk-Forward Matrix': Robustness score didn't pass." —
        and None when no task ever filtered it. 🔬 2026-09-26: with DeleteFailedStrategies
        false a strategy that fails the WFM area rule stays in the databank carrying this.
    """
    with zipfile.ZipFile(path) as z:
        found = re.search(
            r"<FiltersResultFailedReason[^>]*>([^<]*)<",
            z.read("settings.xml").decode("utf-8", "replace"),
        )
    return found.group(1).strip() if found else None
