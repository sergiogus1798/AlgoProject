"""The rows a finished build (step 6) and a WFM reading (step 19) write themselves, live."""

import re
from pathlib import Path

import pandas as pd

from core import assetdata
from ledger import blind, record, study as studymod
from sqx.projects import registry

# SQX's own line at the end of a Build task, in the project's `log/global_log_*.log`.
BUILT = re.compile(r"Strategies generated: (\d+),.*?Accepted: (\d+), Rejected: (\d+)")
GENERATED_UNIT = (
    "generated"  # looks that count toward N but are not a Sharpe: never in sigma
)


def signed(project: str) -> tuple[str, dict] | None:
    """The study a project's rows belong to (symbol, timeframe, template folder), or None.

    Same identity as `ui.daemon.filters.ledgerrow.signed`; None when the registry names no template.
    """
    row = next(
        (
            r
            for r in reversed(registry.rows())
            if r["name"] == project and r["template"]
        ),
        None,
    )
    if row is None:
        return None
    family = Path(row["template"]).parent.name
    return studymod.study_id(row["symbol"], row["timeframe"], family), row


def built(log_dir: Path, since: float = 0.0) -> tuple[int, int] | None:
    """(generated, accepted) of the last Build task SQX logged since `since` (epoch seconds)."""
    last = None
    for file in sorted(
        log_dir.glob("global_log_*.log"), key=lambda f: f.stat().st_mtime
    ):
        if file.stat().st_mtime >= since:
            for m in BUILT.finditer(file.read_text(encoding="utf-8", errors="replace")):
                last = (int(m.group(1)), int(m.group(2)))
    return last


def log_build(project: str, log_dir: Path, since: float = 0.0) -> str:
    """Write step 6's row: n_in = generated by the genetic search, n_out = accepted.

    `n_scored` = generated with unit "generated": it adds to N (the search that was never
    counted) and stays out of sigma, since no Sharpe was kept.

    Returns:
        The line to print: the study written, or why nothing was.
    """
    sign, got = signed(project), built(log_dir, since)
    if sign is None or got is None:
        return "Ledger: sin plantilla en registry.csv o sin línea «Strategies generated» en el log"
    sid, row = sign
    record.log(
        sid,
        {
            "step": 6,
            "launched_by": "ventana",
            "symbol": row["symbol"],
            "timeframe": row["timeframe"],
            "segment": "build",
            "n_in": got[0],
            "n_out": got[1],
            "n_scored": got[0],
            "score_unit": GENERATED_UNIT,
            "criterion": "build: SQX generó n_in y aceptó n_out (su línea «Strategies generated»)",
            "note": f"proyecto {project}",
        },
    )
    return f"Ledger: build {got[0]} generadas, {got[1]} aceptadas, en {sid}"


def log_wfm(project: str, export: Path, n: int, command: str) -> str:
    """Write step 19's rows (build, oos1, oos2 — the matrix reads all three) live.

    Args:
        project: Project name.
        export: The WFM export folder; its path is the note, so re-reading the same export
            writes nothing twice (the ledger cannot take a line back).
        n: Strategies the matrix judged.
        command: The command line, as `launched_by`.
    """
    sign = signed(project)
    if sign is None:
        return "Ledger: sin plantilla en registry.csv: la WFM no se apunta"
    sid, row = sign
    note = f"wfm · {export}"
    frame = studymod.read(sid)
    if len(frame) and (frame["note"].fillna("") == note).any():
        return f"Ledger: {export} ya está apuntado en {sid}"
    for segment in blind.SEGMENTS:
        record.log(
            sid,
            {
                "step": 19,
                "launched_by": command,
                "symbol": row["symbol"],
                "timeframe": row["timeframe"],
                "segment": segment,
                "n_in": n,
                "n_out": n,
                "criterion": "wfm/l1_mediana_exceso+l1_p_menos",
                "note": note,
            },
        )
    return f"Ledger: tres filas del paso 19 en {sid}"


def log_cut(
    project: str, step: float, cut: tuple[int, int], criterion: str, launched_by: str
) -> str:
    """Sign a cut a study made by hand on oos1: one row, unless the workflow runs it.

    Inside the workflow (`ALGO_AUTONOMOUS=1`) `pipeline.autopilot.judge.ledger_row` signs the
    step's cut once, so the study's own row would count the same search twice.

    Args:
        project: Project name, as `registry.csv` knows it.
        step: Workflow step the study belongs to.
        cut: (entered, survived); equal for a reading that removes nothing.
        criterion: What was cut on.
        launched_by: The command.

    Returns:
        The line to print: the study written, or why nothing was.
    """
    if assetdata.enforced():
        return "Ledger: dentro del workflow el corte lo apunta el juez; este estudio no lo repite"
    sign = signed(project)
    if sign is None:
        return "Ledger: sin plantilla en registry.csv: el corte no se apunta"
    sid, row = sign
    record.log(
        sid,
        {
            "step": float(step),
            "launched_by": launched_by,
            "symbol": row["symbol"],
            "timeframe": row["timeframe"],
            "segment": "oos1",
            "n_in": cut[0],
            "n_out": cut[1],
            "criterion": criterion,
            "note": f"proyecto {project}",
        },
    )
    return f"Ledger: {criterion} ({cut[0]} -> {cut[1]}) apuntado en {sid}"


def calib_rows(populations: Path) -> list[tuple[str, dict]]:
    """(study, row) for each calibration population `populations.csv` lists, not yet written.

    Each was built (step 6, `n` strategies in the databank, counted in N as `generated`) and
    then read on its out-of-sample stretch to set step 8's criteria (step 8, oos1, a look that
    adds no candidates). Studies come from the registry; a population it does not know is skipped.
    """
    found = []
    for pop, n in pd.read_csv(populations)[["pop", "n"]].itertuples(index=False):
        sign = signed(pop)
        if sign is None:
            continue
        sid, reg = sign
        base = {
            "launched_by": "ledger.backfill --calib",
            "symbol": reg["symbol"],
            "timeframe": reg["timeframe"],
            "n_in": int(n),
            "n_out": int(n),
            "note": f"backfill calibración · {pop}",
        }
        found += [
            (
                sid,
                {
                    **base,
                    "step": 6,
                    "segment": "build",
                    "n_scored": int(n),
                    "score_unit": GENERATED_UNIT,
                    "criterion": "build de calibración: estrategias del databank",
                },
            ),
            (
                sid,
                {
                    **base,
                    "step": 8,
                    "segment": "oos1",
                    "criterion": "calibración de criterios del paso 8, leída en OOS",
                },
            ),
        ]
    return found
