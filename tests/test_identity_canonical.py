#!/usr/bin/env python3
"""Known answers for the canonical identity: every rewrite SQX was seen making keeps it, a real change moves it.

`tests/fixtures/identity/` holds one (build, after) pair per case, each archive the definition
only; `SOURCES.json` names the file each real one came from. `retest_oos`, `crossmarket`,
`mother_copy` and `signal` are real pairs; `wfm_reordered` is real too (the WFM writes the same
variables in another order). `autogenerated` and `inlined_variable` apply the rewrite to a real
build file exactly as SQX does it — the real twins of 2026-10-16 are on gorilla. The regex identity
of before encargo 76 failed `wfm_reordered` and `inlined_variable`.
"""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from core import sqxfile

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "identity"
SAME = (
    "retest_oos",
    "crossmarket",
    "mother_copy",
    "signal",
    "wfm_reordered",
    "autogenerated",
    "inlined_variable",
)
OTHER = ("reused_name", "param_moved")


def _pair(case: str) -> tuple[str, str]:
    """The identities of a case's two files."""
    return tuple(
        sqxfile.identity(FIXTURES / f"{case}.{side}.sqx") for side in ("build", "after")
    )


@pytest.mark.parametrize("case", SAME)
def test_a_cosmetic_rewrite_keeps_the_identity(case: str) -> None:
    """SQX's rewrite of the text is not another strategy."""
    build, after = _pair(case)
    assert build == after, case


@pytest.mark.parametrize("case", OTHER)
def test_two_different_strategies_keep_two_identities(case: str) -> None:
    """A reused name, or one parameter moved, is another strategy."""
    build, after = _pair(case)
    assert build != after, case


def test_free_text_and_slots_do_not_count_but_a_slot_does() -> None:
    """A UUID in the description changes nothing; which signal a rule reads does."""
    text = sqxfile.rules(FIXTURES / "retest_oos.build.sqx")
    assert "<Description />" in text
    stamped = text.replace("<Description />", "<Description>uuid 1234</Description>", 1)
    assert sqxfile._hashed(stamped) == sqxfile._hashed(text)
    long_entry, short_entry = (
        ">33333333-1111-1111-3333-333333333333</Param>",
        ">33333333-2222-1111-3333-333333333333</Param>",
    )
    assert long_entry in text
    swapped = text.replace(long_entry, short_entry, 1)
    assert sqxfile._hashed(swapped) != sqxfile._hashed(text)


# (category, what the build file says, what another strategy says instead)
CHANGES = (
    ("money management", '<MoneyManagement type="FixedSize">', '<MoneyManagement type="RiskFixedPctOfAccount">'),
    ("lot size", 'varname="null" type="double">0.1</Param>', 'varname="null" type="double">0.2</Param>'),
    ("global stop loss", '<globalSL>\r\n          <values type="fixed">\r\n            <value>0<', '<globalSL>\r\n          <values type="fixed">\r\n            <value>50<'),
    ("order type", 'key="EnterAtMarket"', 'key="EnterAtStop"'),
    ("timeframe", "<timeFrame>0</timeFrame>", "<timeFrame>60</timeFrame>"),
    ("symbol", "<symbol>NULL</symbol>", "<symbol>EURUSD</symbol>"),
    ("snippet", 'key="ATRTrailingStops"', 'key="SuperTrend"'),
)  # fmt: skip


@pytest.mark.parametrize("category,was,becomes", CHANGES, ids=[c[0] for c in CHANGES])
def test_a_change_of_logic_moves_the_identity(
    category: str, was: str, becomes: str
) -> None:
    """Each kind of setting that moves a backtest moves the identity."""
    text = sqxfile.rules(FIXTURES / "retest_oos.build.sqx")
    assert was in text, category
    assert sqxfile._hashed(text.replace(was, becomes, 1)) != sqxfile._hashed(text), (
        category
    )


def _counter(saved: str, read_as_variable: bool) -> str:
    """retest_oos.build with a variable a rule writes (AssignVariable) and then reads."""
    text = sqxfile.rules(FIXTURES / "retest_oos.build.sqx")
    read = (
        '<Param key="#Variable#" variable="true">Counter1</Param>'
        if read_as_variable
        else f'<Param key="#Variable#">{saved}</Param>'
    )
    rule = (
        '<Then>\n<Item key="AssignVariable"><Param key="#Variable#" variable="true">Counter1</Param>'
        '<Param key="#Value#" type="double">1</Param></Item>\n'
        f'<Item key="IntVariable">{read}</Item>'
    )
    variable = (
        f"<variable><id>Counter1</id><name>Counter1</name><type>int</type><value>{saved}</value>"
        "</variable>\n    </Variables>"
    )
    return text.replace("<Then>", rule, 1).replace("</Variables>", variable, 1)


def test_a_written_variable_is_a_slot_not_its_saved_value() -> None:
    """A variable a rule assigns saves the last bar's state: that state is not another strategy,
    and reading it is not the same as reading a literal of that value."""
    assert sqxfile._hashed(_counter("0", True)) == sqxfile._hashed(_counter("7", True))
    assert sqxfile._hashed(_counter("7", True)) != sqxfile._hashed(_counter("7", False))
