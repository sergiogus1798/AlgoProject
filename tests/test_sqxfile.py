#!/usr/bin/env python3
"""Golden-file test for core.sqxfile: a parser that breaks silently poisons every analysis."""

import collections
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from core import sqxfile

FIXTURE = Path(__file__).parent / "fixtures" / "strategy.sqx"
GOLDEN = Path(__file__).parent / "fixtures" / "strategy.golden.json"


def parse() -> dict:
    """Everything core.sqxfile reads out of the fixture strategy.

    Returns:
        Identity hash, symbol and feed, every parameter, and a census of the rule tree —
        the census catches an XML change the flat fields would miss.
    """
    blocks = collections.Counter(
        (item.get("categoryType"), item.get("key")) for item in sqxfile.xml(FIXTURE).iter("Item"))
    return {"identity": sqxfile.identity(FIXTURE),
            "symbol": list(sqxfile.symbol(FIXTURE)),
            "parameters": sqxfile.parameters(FIXTURE),
            "blocks": {f"{c}/{k}": n for (c, k), n in sorted(blocks.items(), key=str)},
            # Known-answer (OPEN #17): 4 ParamTypePeriod + 3 ParamTypeExitUsed by hand count
            # in strategy_Portfolio.xml's <Variables>, MagicNumber and the two signal
            # variables excluded — never SQX's frozen ParameterCount.
            "param_count": sqxfile.param_count(FIXTURE)}


def main() -> None:
    """Compare against the golden file, or write it when run with --bless."""
    # Known-answer (OPEN #97): a dot, a lowercase letter or an `@` is part of the symbol.
    for entry, want in (("Results/Main: UKOIL.cash_M1_LOM_H1/x", ("UKOIL.cash", "M1_LOM_H1")),
                        ("Results/Main: SP500ft_Plus02_Infinox/x", ("SP500ft", "Plus02_Infinox")),
                        ("Results/Main: @ES_D1/x", ("@ES", "D1")),
                        ("Results/Main: XAUUSD_M1_LOM_M30/x", ("XAUUSD", "M1_LOM_M30"))):
        assert sqxfile.RESULTS_RE.search(entry).groups() == want, entry
    # The identity drops each cosmetic attribute with the whitespace before it, exactly as
    # the `\s*`-led regex it replaced on 2026-10-04 did.
    led = re.compile(r'\s*(?:makeExternal|autoGenerated)="[^"]*"')
    for text in ('<v a="1"\n\t makeExternal="true" autoGenerated="x"  b="2"/>',
                 'xmakeExternal=""y  autoGenerated="true"', "nothing cosmetic  "):
        want = hashlib.sha256(led.sub("", text).encode("utf-8")).hexdigest()
        assert sqxfile._hashed(text) == want, text
    result = parse()
    if "--bless" in sys.argv:
        GOLDEN.write_text(json.dumps(result, indent=2), encoding="utf-8")
        print(f"blessed {GOLDEN}")
        return
    expected = json.loads(GOLDEN.read_text(encoding="utf-8"))
    if result == expected:
        print("test_sqxfile: ok")
        return
    print("test_sqxfile: FAILED — core.sqxfile no longer reads this strategy the same way")
    print(json.dumps(result, indent=2)[:2000])
    sys.exit(1)


if __name__ == "__main__":
    main()
